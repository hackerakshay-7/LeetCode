class Solution {
    public long countCommas(long n) {
      long ans =0;
        int commas =1;
        for(long i =1000;i<=n;i*=1000){
            long a = Math.min(n,i*1000-1);
            ans= ans + commas*(a-i+1);
            commas++;
        }
   return ans; }
}
